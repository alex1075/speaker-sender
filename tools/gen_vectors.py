#!/usr/bin/env python3
# Regenerates tests/vectors.h from the reference implementations the C code must agree with
# (pyatv + srptools + cryptography). Needs: pip install pyatv srptools cryptography
import binascii
import hashlib
import plistlib
import struct
import sys

from srptools import SRPContext, SRPClientSession, constants
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.kdf.hkdf import HKDF
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305
from pyatv.support.chacha20 import Chacha20Cipher8byteNonce

def hexArray(name, data):
    li = []
    for i in range(0, len(data), 12):
        li.append('    ' + ', '.join('0x%02x' % b for b in data[i:i + 12]))
    return 'static const uint8_t ' + name + '[' + str(len(data)) + '] = {\n' + ',\n'.join(li) + '\n};\n'

def hkdf_expand(salt, info, ikm):
    return HKDF(algorithm=hashes.SHA512(), length=32, salt=salt.encode(), info=info.encode()).derive(ikm)

def alac_ref(pcm_be):
    header = (0b001 << 20) | 1
    nbits = len(pcm_be) * 8
    value = (header << nbits) | int.from_bytes(pcm_be, 'big')
    value = (value << 3) | 0b111
    total = 23 + nbits + 3
    pad = (-total) % 8
    return (value << pad).to_bytes((total + pad) // 8, 'big')

def pattern(n, mul, add):
    return bytes([(i * mul + add) & 0xff for i in range(n)])

def srpVectors():
    a = bytes(range(1, 33))
    salt = bytes(range(0x40, 0x50))
    bpriv = bytes(range(0x80, 0xa0))
    N = int(constants.PRIME_3072.replace('\n', '').replace(' ', ''), 16)
    B = pow(5, int.from_bytes(bpriv, 'big'), N).to_bytes(384, 'big')
    ctx = SRPContext('Pair-Setup', '3939', prime=constants.PRIME_3072, generator=constants.PRIME_3072_GEN, hash_func=hashlib.sha512)
    sess = SRPClientSession(ctx, binascii.hexlify(a).decode())
    sess.process(binascii.hexlify(B).decode(), binascii.hexlify(salt).decode())
    K = binascii.unhexlify(sess.key)
    M1 = binascii.unhexlify(sess.key_proof)
    A = binascii.unhexlify(sess.public)
    out = hexArray('V_SRP_A_PRIV', a) + hexArray('V_SRP_SALT', salt) + hexArray('V_SRP_B', B)
    out += hexArray('V_SRP_A_MIN', A) + hexArray('V_SRP_K', K) + hexArray('V_SRP_M1', M1)
    return out, K

def main():
    out = '/* generated by tools/gen_vectors.py - do not edit */\n#include <stdint.h>\n'
    srp, K = srpVectors()
    out += srp
    out += hexArray('V_HKDF_CONTROL_WRITE', hkdf_expand('Control-Salt', 'Control-Write-Encryption-Key', K))
    out += hexArray('V_HKDF_EVENTS_READ', hkdf_expand('Events-Salt', 'Events-Read-Encryption-Key', K))
    key = bytes(range(32))
    nonce = bytes(4) + (5).to_bytes(8, 'little')
    pt = pattern(37, 5, 1)
    out += hexArray('V_AEAD_KEY', key) + hexArray('V_AEAD_PT', pt)
    out += hexArray('V_AEAD_CT', ChaCha20Poly1305(key).encrypt(nonce, pt, b'\x25\x00'))
    shk = bytes(range(100, 132))
    pcm = pattern(1408, 7, 3)
    cipher = Chacha20Cipher8byteNonce(shk, shk)
    header = struct.pack('!BBHII', 0x80, 0xe0, 0x1234, 66150, 0xdeadbeef)
    pkt = b''
    for i in range(3):
        nonce8 = cipher.out_nonce
        enc = cipher.encrypt(pcm, aad=header[4:12])
        pkt = header + enc + nonce8[-8:]
    out += hexArray('V_AUDIO_KEY', shk) + hexArray('V_AUDIO_PCM', pcm)
    out += hexArray('V_AUDIO_PKT3', pkt)
    out += hexArray('V_ALAC', alac_ref(pcm))
    out += hexArray('V_SYNC', struct.pack('!BBHIIII', 0x90, 0xd4, 7, 1000, 0xe9c1a2b3, 0x12345678, 67150))
    req = struct.pack('!BBHIIIIIII', 0x80, 0xd2, 7, 0, 0, 0, 0, 0, 0xe9c1a2b3, 0x01020304)
    rep = struct.pack('!BBHIIIIIII', 0x80, 0xd3, 7, 0, 0xe9c1a2b3, 0x01020304, 0xe9c1a2c0, 0x0a0b0c0d, 0xe9c1a2c0, 0x0a0b0c0d)
    out += hexArray('V_TIMING_REQ', req) + hexArray('V_TIMING_REP', rep)
    d = {'streams': [{'audioFormat': 0x800, 'audioMode': 'default', 'controlPort': 50000, 'ct': 1, 'isMedia': True,
                      'latencyMax': 88200, 'latencyMin': 11025, 'shk': shk, 'spf': 352, 'sr': 44100, 'type': 0x60,
                      'supportsDynamicStreamID': False, 'streamConnectionID': 3735928559}],
         'name': 'café ♫', 'ratio': 1.5, 'big': 4294967296}
    out += hexArray('V_BPLIST', plistlib.dumps(d, fmt=plistlib.FMT_BINARY))
    sys.stdout.write(out)

main()
